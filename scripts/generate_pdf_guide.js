let rY = tableY + 22;
rows.forEach((r, idx) => {
  if (idx % 2 === 1) doc.rect(40, rY - 2, 515, 17).fill('#f8fafc');
  doc.fillColor(TEXT_DARK).fontSize(8.5).font('Helvetica');
  doc.text(r[0], 50, rY);
  doc.text(r[1], 240, rY);
  doc.text(r[2], 400, rY);
  rY += 17;
});

doc.y = tableY + 102;

drawInfoBox('Important Note on Paid Rest Breaks', [
  '• 10-minute Rest Breaks are PAID by law and are NEVER deducted from your timecard hours.',
  '• Only the 30-minute Lunch Break is unpaid and deducted from gross shift hours.'
], WARNING);

// ==========================================
// PAGE 3: TIME CLOCK, SWAPS, LEAVE & UPDATES
// ==========================================
doc.addPage();
drawHeader('Time Clock & Requests');

drawSectionHeading('5', 'Time Clock Terminal & Geofencing');
drawParagraph('Staff members clock in and out using the digital Time Clock Terminal.');
drawBullet('Geofencing Protection', 'To ensure compliance, clocking in requires location access and must be within ~500m of Amcal Pharmacy Woy Woy (-33.4842, 151.3259).');
drawBullet('Clocking In', 'Select your name from the dropdown and click "Clock In".');
drawBullet('Starting 30m Lunch Break', 'Click "30m Lunch (Unpaid)" when taking your unpaid meal break.');
drawBullet('Starting 10m Paid Rest Break', 'Click "10m Rest (Paid)" when taking your 10-minute tea/rest break.');
drawBullet('Ending Break', 'Click "End Break" to resume active duty status.');
drawBullet('Clocking Out', 'Click "Clock Out" at the end of your shift.');

drawSectionHeading('6', 'Shift Swaps & Peer Cover Requests');
drawParagraph('If you are unable to work a scheduled shift, you can initiate a shift swap:');
drawBullet('Submitting a Swap Request', 'Open the Shift Swap Board -> click "Request Shift Swap" -> select your shift and the target staff member.');
drawBullet('Peer Notification', 'The selected colleague will see the cover request on their scheduler badge.');
drawBullet('Manager Approval', 'Once the colleague agrees, the Manager approves the swap, automatically updating the roster.');

drawSectionHeading('7', 'Requesting Time Off / Leave');
drawParagraph('Submit leave requests directly in the app for Manager review.');
drawBullet('Types of Leave', 'Select Annual Leave, Sick Leave, Carer\'s Leave, or Unpaid Leave.');
drawBullet('Dates & Reason', 'Specify start date, end date, and any relevant notes (e.g. medical certificate attached).');
drawBullet('Approval Status', 'Track real-time status (Pending, Approved, Rejected) under the Time Off tab.');

drawSectionHeading('8', 'System Updates & Technical Support');
drawBullet('English Update Log (Release Notes)', 'Click the "Updates (v9.2.9)" button in the top navigation bar to review recent system improvements, live pay calculations, and Fair Work 2026 features.');
drawBullet('Technical Support', 'For assistance with logins or rosters, contact the Pharmacist Manager or system administrator.');

// --- Footer for all pages ---
const totalPages = doc.bufferedPageRange().count;
for (let i = 0; i < totalPages; i++) {
  doc.switchToPage(i);
  doc.rect(40, 780, 515, 20).fill(PRIMARY);
  doc.fillColor('#ffffff').fontSize(8).font('Helvetica')
     .text('Amcal Pharmacy Woy Woy - Confidential Roster Operations Manual', 50, 786, { lineBreak: false });
  doc.text(`Page ${i + 1} of ${totalPages}`, 450, 786, { align: 'right', width: 95, lineBreak: false });
}

doc.end();

stream.on('finish', () => {
  console.log(`✅ PDF User Guide generated successfully at: ${outputPath}`);
  
  // Auto-generate Serverless Guide Download API Endpoint
  const guideApiDir = path.join(__dirname, '..', 'api', 'schedule', 'guide');
  if (!fs.existsSync(guideApiDir)) fs.mkdirSync(guideApiDir, { recursive: true });
  
  const guideApiContent = `import type { VercelRequest, VercelResponse } from '@vercel/node';
import fs from 'fs';
import path from 'path';

export default function handler(req: VercelRequest, res: VercelResponse) {
  const origin = (req.headers.origin as string) || '';
  const allowedOrigins = [
    'https://woywoyamcalroster.vercel.app',
    'http://localhost:3000',
    'http://localhost:3002',
    'http://127.0.0.1:3000',
    'http://localhost:5173'
  ];
  if (allowedOrigins.includes(origin) || origin.endsWith('.vercel.app')) {
    res.setHeader('Access-Control-Allow-Origin', origin);
  } else {
    res.setHeader('Access-Control-Allow-Origin', 'https://woywoyamcalroster.vercel.app');
  }
  res.setHeader('Access-Control-Allow-Methods', 'GET, OPTIONS');
  res.setHeader('Access-Control-Allow-Headers', 'Content-Type');
  if (req.method === 'OPTIONS') return res.status(200).end();

  try {
    const pdfPath = path.join(process.cwd(), 'Amcal_Woy_Woy_Staff_User_Guide.pdf');
    if (!fs.existsSync(pdfPath)) {
      return res.status(404).json({ error: 'Staff User Guide PDF not found on server.' });
    }

    const fileBuffer = fs.readFileSync(pdfPath);
    res.setHeader('Content-Type', 'application/pdf');
    res.setHeader('Content-Disposition', 'attachment; filename="Amcal_Woy_Woy_Staff_User_Guide.pdf"');
    res.setHeader('Content-Length', fileBuffer.length);
    res.setHeader('Cache-Control', 'public, max-age=3600');
    return res.status(200).send(fileBuffer);
  } catch (err) {
    const msg = err instanceof Error ? err.message : 'Unknown error';
    console.error('[GuideAPI] Error:', msg);
    return res.status(500).json({ error: msg });
  }
}
`;
  fs.writeFileSync(path.join(guideApiDir, 'index.ts'), guideApiContent, 'utf8');
  console.log(`✅ Guide API endpoint generated at: ${path.join(guideApiDir, 'index.ts')}`);
});
