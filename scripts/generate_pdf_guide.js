drawSubHeading('1.1 Web Access & PWA Mobile Installation');
drawBullet('Canonical Web Address', 'Access the system from any browser at https://woywoyamcalroster.vercel.app');
drawBullet('iPhone (iOS) Installation', 'Open Safari -> tap the Share icon -> select "Add to Home Screen".');
drawBullet('Android Installation', 'Open Chrome -> tap the three dots menu -> select "Install App" or "Add to Home Screen".');

