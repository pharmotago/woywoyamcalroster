const PDFDocument = require('pdfkit');
const fs = require('fs');
const path = require('path');

const outputPath = path.join(__dirname, '..', 'Amcal_Woy_Woy_Staff_User_Guide.pdf');
const doc = new PDFDocument({
  size: 'A4',
  margin: 40,
  bufferPages: true,
  info: {
    Title: 'Amcal Pharmacy Woy Woy - Staff Operating Manual',
    Author: 'Amcal Woy Woy Management',
    Subject: 'Amcal Woy Woy Roster - Employee User Guide & Operations Manual',
    Keywords: 'Amcal, Pharmacy, Roster, Staff Guide, Pharmacy Award 2026, Time Clock'
  }
});

const stream = fs.createWriteStream(outputPath);
doc.pipe(stream);

// --- Theme Colors ---
const PRIMARY = '#0f172a';    // Dark Navy
const ACCENT = '#0284c7';     // Cyan Blue
const SUCCESS = '#059669';    // Emerald Green
const WARNING = '#d97706';    // Amber
const TEXT_DARK = '#1e293b';  // Slate Dark
const TEXT_MUTED = '#64748b'; // Slate Muted
const BG_LIGHT = '#f8fafc';   // Light Gray Box
const BORDER = '#e2e8f0';

function drawHeader(title) {
  doc.rect(40, 40, 515, 50).fill(PRIMARY);
  
  // Amcal Brand Mark
  doc.fillColor('#ffffff').fontSize(18).font('Helvetica-Bold').text('Amcal+', 55, 52);
  doc.fillColor(ACCENT).fontSize(10).font('Helvetica-Bold').text('WOY WOY ROSTER', 130, 58);
  
  doc.fillColor('#ffffff').fontSize(11).font('Helvetica-Bold').text(title.toUpperCase(), 320, 56, { align: 'right', width: 220 });
}

function drawSectionHeading(num, title) {
  doc.moveDown(0.8);
  const y = doc.y;
  doc.rect(40, y, 515, 24).fill(BG_LIGHT);
  doc.rect(40, y, 4, 24).fill(ACCENT);
  doc.fillColor(TEXT_DARK).fontSize(12).font('Helvetica-Bold').text(`${num}. ${title}`, 52, y + 6);
  doc.moveDown(0.6);
}

function drawSubHeading(title) {
  doc.moveDown(0.4);
  doc.fillColor(ACCENT).fontSize(10).font('Helvetica-Bold').text(title);
  doc.moveDown(0.2);
}

function drawParagraph(text) {
  doc.fillColor(TEXT_DARK).fontSize(9.5).font('Helvetica').text(text, { lineGap: 3 });
  doc.moveDown(0.3);
}

function drawBullet(title, text) {
  const y = doc.y;
  doc.fillColor(ACCENT).fontSize(10).text('•', 48, y);
  doc.fillColor(TEXT_DARK).fontSize(9.5).font('Helvetica-Bold').text(`${title}: `, 60, y, { continued: true });
  doc.font('Helvetica').text(text, { lineGap: 2 });
  doc.moveDown(0.25);
}

function drawInfoBox(title, lines, color = ACCENT) {
  doc.moveDown(0.4);
  const startY = doc.y;
  const boxHeight = (lines.length * 14) + 24;
  
  doc.rect(40, startY, 515, boxHeight).fill('#f0f9ff').stroke(BORDER);
  doc.rect(40, startY, 4, boxHeight).fill(color);
  
  doc.fillColor(color).fontSize(9.5).font('Helvetica-Bold').text(`[NOTE] ${title}`, 52, startY + 8);
  
  let currY = startY + 22;
  lines.forEach(line => {
    doc.fillColor(TEXT_DARK).fontSize(8.8).font('Helvetica').text(line, 52, currY);
    currY += 13;
  });
  
  doc.y = startY + boxHeight + 6;
}

// ==========================================
// PAGE 1: COVER & SYSTEM ACCESS
// ==========================================
drawHeader('Staff Operating Manual');

doc.moveDown(2);
doc.fillColor(PRIMARY).fontSize(20).font('Helvetica-Bold').text('Amcal Pharmacy Woy Woy');
doc.fillColor(ACCENT).fontSize(14).font('Helvetica-Bold').text('Staff Roster & Time Clock System Operations Guide (v9.2.8)');
doc.fillColor(TEXT_MUTED).fontSize(9).font('Helvetica').text('Published: August 2026 | System Edition v9.2.8 | Canonical App: https://woywoyamcalroster.vercel.app');

doc.moveDown(1);

drawSectionHeading('1', 'System Overview & App Access');
